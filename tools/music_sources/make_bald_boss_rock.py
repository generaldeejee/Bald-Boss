def speak_line(text, male=True, pitch=50, rate=145):
    voice='en-us+m3' if male else 'en-us+f3'
    result=subprocess.run(['espeak','-v',voice,'-p',str(pitch),'-s',str(rate),'-a','175','--stdout',text],stdout=subprocess.PIPE,stderr=subprocess.DEVNULL,check=True)
    with wave.open(io.BytesIO(result.stdout),'rb') as wf:
        source_rate=wf.getframerate()
        data=np.frombuffer(wf.readframes(wf.getnframes()),dtype='<i2').astype(np.float32)/32768.0
    y=resample_poly(data,SR,source_rate).astype(np.float32)
    return y

for idx,(bar,line) in enumerate(LYRIC_LINES):
    chorus = is_chorus(bar) or bar>=36
    voice_pitch=56 if chorus else 41
    speed=142 if chorus else 163
    y=speak_line(line,pitch=voice_pitch,rate=speed)
    if chorus:
        # hype-man chant with flutter and phaser-like second copy
        tt=np.arange(len(y),dtype=np.float32)/SR
        flutter=(.84+.16*np.sin(2*np.pi*5.9*tt))
        y=np.tanh(y*2.5)*flutter
        y=filt(y,low=130,high=4500)
        amp=.33
    else:
        y=np.tanh(y*1.6); y=filt(y,low=130,high=6000)
        amp=.21
    start=at(bar,.18)
    mix(start,y,amp,pan=-.08,dest=vocals)
    # doubles, like a very small futuristic crowd of barbers
    if chorus:
        y2=speak_line(line,male=False,pitch=41,rate=speed+8)
        y2=np.tanh(y2*2.2)
        y2=filt(y2,low=230,high=4400)
        mix(start+.085,y2,.15,pan=.28,dest=vocals)
    for delay,volume in ((.18,.10),(.36,.07)):
        mix(start+delay,y,volume,pan=.23 if delay<.2 else -.2,dest=vocals)

# Mix, soft compression and tame sub frequencies without requiring external samples.
def finalize(waveform, peak=.925):
    y=waveform.copy()
    y-=np.mean(y,axis=0,keepdims=True)
    # Saturation prevents clipping and adds grit to faux-rock instruments.
    y=np.tanh(y*1.35)
    mx=np.max(np.abs(y))
    if mx>1e-7: y*=peak/mx
    return y

instrumental=finalize(music)
full=finalize(music+vocals,peak=.92)

# Mono-friendly stereo & tiny fade ending.
fade_samples=int(.6*SR)
for y in [instrumental,full]:
    y[-fade_samples:]*=np.linspace(1,0,fade_samples,dtype=np.float32)[:,None]

sf.write(OUT/'Bald_Boss_No_Hair_No_Fear.wav',full,SR,subtype='PCM_16')
subprocess.run(['ffmpeg','-y','-loglevel','error','-i',str(OUT/'Bald_Boss_No_Hair_No_Fear.wav'),'-c:a','libvorbis','-q:a','5',str(OUT/'Bald_Boss_No_Hair_No_Fear.ogg')],check=True)
sf.write(OUT/'Bald_Boss_No_Hair_No_Fear_Instrumental.wav',instrumental,SR,subtype='PCM_16')
subprocess.run(['ffmpeg','-y','-loglevel','error','-i',str(OUT/'Bald_Boss_No_Hair_No_Fear_Instrumental.wav'),'-c:a','libvorbis','-q:a','5',str(OUT/'Bald_Boss_No_Hair_No_Fear_Instrumental.ogg')],check=True)
# An instrumental gameplay loop: eight-bar chorus section, crossfade 0.1s at wrap.
loop=instrumental[int(at(16)*SR):int(at(24)*SR)].copy()
f=int(.12*SR)
# Smooth transition for repeat playback.
end=loop[-f:].copy(); beginning=loop[:f].copy()
loop[:f]=beginning*np.linspace(0,1,f)[:,None]+end*np.linspace(1,0,f)[:,None]
loop[-f:]=loop[:f]
sf.write(OUT/'Bald_Boss_Gameplay_Loop.wav',loop,SR,subtype='PCM_16')
subprocess.run(['ffmpeg','-y','-loglevel','error','-i',str(OUT/'Bald_Boss_Gameplay_Loop.wav'),'-c:a','libvorbis','-q:a','5',str(OUT/'Bald_Boss_Gameplay_Loop.ogg')],check=True)
(OUT/'Bald_Boss_No_Hair_No_Fear_Lyrics.txt').write_text('''BALD BOSS — NO HAIR, NO FEAR!\nOriginal music and lyrics for the Bald Boss game\n\n[Verse]\nMirror, mirror, clear the way\nEvery hair has had its day\nClippers buzzing, feel the power\nTime to shine, this is the hour\n\n[Pre-Chorus]\nRaise your razors, make it clear\nThe shiny legend now is here!\n\n[Chorus]\nNO HAIR! NO FEAR!\nBALD BOSS IS HERE!\nSHAVE IT OFF! MAKE IT CLEAR!\nSHINY HEADS, WE CHEER!\n\n[Instrumental hair-metal-style solo]\n\n[Chorus — repeat]\nNO HAIR! NO FEAR!\nBALD BOSS IS HERE!\nSHAVE IT OFF! MAKE IT CLEAR!\nSHINY HEADS, WE CHEER!\n\n[Outro]\nBALD BOSS!\nNO HAIR, NO FEAR!\n\nVocal sound: intentionally robotic chant generated with offline eSpeak text-to-speech.\nInstruments: fully procedurally synthesized (no borrowed songs or samples).\n''',encoding='utf-8')
