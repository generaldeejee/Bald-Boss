#!/usr/bin/env python3
"""Build-time conversion of Bald Boss ORIGINAL Deep Voice soundtrack to PSP PCM8.

Regenerates BOTH game tracks from the included openly readable source scripts:
- deep-voice song for title/results
- matching instrumental for gameplay
The PSP can play these directly without an expensive OGG decoder.
Dependencies (build host only): numpy, scipy, soundfile, ffmpeg, piper-tts==1.3.0.
The expressive Piper model is cached on the build computer and NEVER stored
inside the PSP executable. The instrumental is left unchanged.
"""
from pathlib import Path
import subprocess
import sys
import numpy as np
import soundfile as sf
from scipy.signal import resample_poly

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "music_sources"
DST = ROOT / "src" / "music_samples.h"
subprocess.run([sys.executable, str(SRC / "make_bald_boss_deep_voice.py")], check=True, cwd=SRC)

def encode(p):
    audio, rate = sf.read(str(p), always_2d=True, dtype="float32")
    if rate != 44100:
        raise ValueError("Expected 44.1-kHz soundtrack: " + str(p))
    mono = audio.mean(axis=1)  # stereo -> mono for PSP memory/performance
    low = resample_poly(mono, 1, 4).astype(np.float32)
    low = np.clip(low, -1, 1)
    # Use about 98% range without clipping around the int8 center.
    pcm = np.clip(np.rint(low * 125.0 + 128.0), 0, 255).astype(np.uint8)
    if len(pcm) < 20_000 or len(pcm) > 900_000:
        raise ValueError("Unexpected music length: " + str(len(pcm)))
    return pcm

full = encode(SRC / "Bald_Boss_80s_Deep_Voice.wav")
inst = encode(SRC / "Bald_Boss_80s_Deep_Instrumental.wav")
if len(full) != len(inst):
    raise ValueError("Full/instrumental versions must be frame-aligned")

parts = [
 "/* AUTOGENERATED. Original Bald Boss soundtrack with expressive Piper male spoken-rock vocals. */",
 "#ifndef BALD_BOSS_MUSIC_SAMPLES_H",
 "#define BALD_BOSS_MUSIC_SAMPLES_H",
 "#define BALD_MUSIC_SAMPLE_RATE 11025",
 "#define BALD_BOSS_MUSIC_VOCALS_PIPER 1",
 f"#define BALD_MUSIC_FULL_LEN {len(full)}",
 f"#define BALD_MUSIC_INSTRUMENTAL_LEN {len(inst)}",
]
for name, pcm in [("bald_music_full", full),("bald_music_instrumental", inst)]:
    parts.append("static const unsigned char " + name +
                 "[] __attribute__((aligned(16))) = {")
    for pos in range(0, len(pcm), 32):
        parts.append(" " + ",".join(f"0x{b:02x}" for b in pcm[pos:pos+32]) + ",")
    parts.append("};")
parts += ["#endif", ""]
DST.write_text("\n".join(parts), encoding="ascii")
print("PSP soundtrack: title/results",len(full),
      "bytes; gameplay instrumental",len(inst),"bytes")
